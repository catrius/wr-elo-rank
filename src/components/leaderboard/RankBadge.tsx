export default function RankBadge({ rank, bottomRank = null }: { rank: number | null; bottomRank?: number | null }) {
  if (rank === null) return <span className="text-gray-400">—</span>;
  const color = MEDAL_COLORS[rank];
  if (color) {
    return (
      <span title={`Rank ${rank}`} className="relative inline-flex h-6 w-6 items-center justify-center">
        <CrownIcon
          className={`
            h-6 w-6 drop-shadow-sm
            ${color}
          `}
        />
        <span
          className={`
            absolute inset-0 flex items-center justify-center pt-1 text-[10px] leading-none font-bold text-white
            [text-shadow:0_1px_2px_rgba(0,0,0,0.7)]
          `}
        >
          {rank}
        </span>
      </span>
    );
  }
  if (bottomRank) {
    const devil = DEVIL_COLORS[bottomRank] ?? DEVIL_COLORS[2];
    return (
      <span
        title={`Rank ${rank} · bottom ${bottomRank}`}
        className="relative inline-flex w-10 items-center justify-center"
      >
        <DevilEmblem className="h-auto w-10 drop-shadow-sm" main={devil.main} highlight={devil.highlight} />
        {/* the heart sits low-center in the artwork, so the number rides ~68% down, not dead center */}
        <span
          className={`
            absolute top-[68%] left-1/2 -translate-x-1/2 -translate-y-1/2 text-[8px] leading-none font-bold text-white
            [text-shadow:0_1px_2px_rgba(0,0,0,0.8)]
          `}
        >
          {rank}
        </span>
      </span>
    );
  }
  return <>{rank}</>;
}
